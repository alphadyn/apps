"""Build an offline ICD-10-CM diagnosis catalog from CMS code-description files."""

import argparse
import datetime
import json
import pathlib
import re
import urllib.request
import zipfile
from io import BytesIO


ROOT = pathlib.Path(__file__).resolve().parents[1]
CMS_SOURCE = "https://www.cms.gov/medicare/coding-billing/icd-10-codes"
ARCHIVE_URL = "https://www.cms.gov/files/zip/{year}-code-descriptions-tabular-order.zip"
CODE_PATTERN = re.compile(r"^[A-Z0-9]{3,7}$")


def build_catalog(year):
    request = urllib.request.Request(
        ARCHIVE_URL.format(year=year),
        headers={"User-Agent": "Northstar EHR diagnosis catalog"},
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        archive_data = response.read()

    member = f"Code Descriptions/icd10cm_codes_{year}.txt"
    with zipfile.ZipFile(BytesIO(archive_data)) as archive:
        text = archive.read(member).decode("ascii")

    diagnoses = []
    seen_codes = set()
    for line in text.splitlines():
        parts = line.split(None, 1)
        if len(parts) != 2:
            continue
        code, name = parts[0].strip(), " ".join(parts[1].split())
        if not CODE_PATTERN.fullmatch(code) or not name or code in seen_codes:
            continue
        seen_codes.add(code)
        formatted_code = f"{code[:3]}.{code[3:]}" if len(code) > 3 else code
        diagnoses.append({"code": formatted_code, "name": name})

    if len(diagnoses) < 10000:
        raise RuntimeError(f"Expected at least 10,000 ICD-10-CM diagnoses; found {len(diagnoses)}")

    return {
        "source": "CMS ICD-10-CM",
        "sourceUrl": CMS_SOURCE,
        "sourceVersion": str(year),
        "retrievedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "count": len(diagnoses),
        "diagnoses": diagnoses,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--year", type=int, default=2027)
    args = parser.parse_args()
    catalog = build_catalog(args.year)
    output = ROOT / "catalogs" / "diagnosis-catalog.js"
    output.write_text(
        "// Generated by scripts/build_diagnosis_catalog.py; CMS ICD-10-CM code descriptions.\n"
        "const icd10cmDiagnosisCatalog = "
        + json.dumps(catalog, ensure_ascii=True, separators=(",", ":"))
        + ";\n"
    )
    print(f"Wrote {catalog['count']} ICD-10-CM diagnoses to {output}")


if __name__ == "__main__":
    main()
