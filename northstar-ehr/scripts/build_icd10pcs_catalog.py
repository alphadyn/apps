"""Build an offline ICD-10-PCS catalog from CMS order files."""

import argparse
import datetime
import json
import pathlib
import re
import urllib.request
import zipfile
from io import BytesIO


ROOT = pathlib.Path(__file__).resolve().parents[1]
CMS_SOURCE = "https://www.cms.gov/medicare/coding-billing/icd-10-codes"
ARCHIVE_URL = (
    "https://www.cms.gov/files/zip/"
    "april-1-{year}-icd-10-pcs-order-file-long-abbreviated-titles.zip"
)
CODE_PATTERN = re.compile(
    r"^\d{5}\s+([0-9A-HJ-NP-Z]{7})\s+\d\s+(.+?)\s{2,}(.+)$"
)


def build_catalog(year):
    request = urllib.request.Request(
        ARCHIVE_URL.format(year=year),
        headers={"User-Agent": "Northstar EHR ICD-10-PCS catalog"},
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        archive_data = response.read()

    member = f"icd10pcs_order_{year}.txt"
    with zipfile.ZipFile(BytesIO(archive_data)) as archive:
        text = archive.read(member).decode("ascii")

    procedures = []
    seen_codes = set()
    for line in text.splitlines():
        match = CODE_PATTERN.match(line)
        if not match:
            continue
        code, abbreviated_title, title = match.groups()
        if code in seen_codes:
            continue
        seen_codes.add(code)
        procedures.append({
            "code": code,
            "name": " ".join(title.split()),
            "abbreviatedName": " ".join(abbreviated_title.split()),
        })

    if len(procedures) < 10000:
        raise RuntimeError(f"Expected at least 10,000 ICD-10-PCS codes; found {len(procedures)}")

    return {
        "source": "CMS ICD-10-PCS",
        "sourceUrl": CMS_SOURCE,
        "sourceVersion": f"April 1, {year}",
        "retrievedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "count": len(procedures),
        "procedures": procedures,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--year", type=int, default=2026)
    args = parser.parse_args()
    catalog = build_catalog(args.year)
    output = ROOT / "catalogs" / "icd10pcs-catalog.js"
    output.write_text(
        "// Generated by scripts/build_icd10pcs_catalog.py; CMS ICD-10-PCS titles.\n"
        "const icd10pcsProcedureCatalog = "
        + json.dumps(catalog, ensure_ascii=True, separators=(",", ":"))
        + ";\n"
    )
    print(f"Wrote {catalog['count']} ICD-10-PCS procedures to {output}")


if __name__ == "__main__":
    main()
