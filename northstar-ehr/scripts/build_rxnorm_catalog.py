"""Build an offline RxNorm clinical-drug snapshot from the public RxNav API."""

import argparse
import datetime
import json
import pathlib
import urllib.request


ROOT = pathlib.Path(__file__).resolve().parents[1]
API = "https://rxnav.nlm.nih.gov/REST"
SOURCE = "RxNorm via RxNav"


def fetch_json(url):
    request = urllib.request.Request(url, headers={"User-Agent": "NorthstarEHR medication catalog"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.load(response)


def build_catalog(count):
    payload = fetch_json(f"{API}/allconcepts.json?tty=SCD")
    concepts = payload.get("minConceptGroup", {}).get("minConcept", [])
    unique = {}
    for concept in concepts:
        name = " ".join(concept.get("name", "").split())
        rxcui = str(concept.get("rxcui", "")).strip()
        if name and rxcui:
            unique.setdefault(name.casefold(), {"name": name, "rxcui": rxcui})
    concepts = sorted(unique.values(), key=lambda item: (item["name"].casefold(), item["rxcui"]))
    if len(concepts) < count:
        raise RuntimeError(f"Need {count} distinct RxNorm products; found only {len(concepts)}")

    # Even spacing across the full name-sorted snapshot avoids selecting only
    # the first alphabetical segment when a capped catalog is requested.
    selected = [
        concepts[(index * len(concepts)) // count]
        for index in range(count)
    ]
    version = fetch_json(f"{API}/version.json").get("version", "Not supplied")
    return {
        "source": SOURCE,
        "sourceUrl": "https://www.nlm.nih.gov/research/umls/rxnorm/",
        "termsUrl": "https://www.nlm.nih.gov/research/umls/rxnorm/docs/termsofuse.html",
        "retrievedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "sourceVersion": version,
        "termType": "SCD",
        "count": count,
        "selection": "Evenly sampled across unique, name-sorted RxNorm SCD concepts. Distinct strengths/forms may be separate products.",
        "limitations": "RxNorm normalized product concepts are not prescribing guidance. The SCD concept list does not provide pharmacologic class, diagnosis/indication, specialty, route, adverse-effect, or interaction coverage.",
        "medications": selected,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--count", type=int, default=10000)
    args = parser.parse_args()
    if args.count < 1:
        parser.error("count must be positive")
    catalog = build_catalog(args.count)
    output = ROOT / "rxnorm-catalog.js"
    output.write_text(
        "// Generated by scripts/build_rxnorm_catalog.py; RxNorm concept metadata only.\n"
        "const rxNormMedicationCatalog = " +
        json.dumps(catalog, ensure_ascii=True, separators=(",", ":")) + ";\n"
    )
    print(f"Wrote {len(catalog['medications'])} distinct RxNorm products to {output}")


if __name__ == "__main__":
    main()
