"""Refresh the bundled high-resolution Picsum catalog."""

import json
from pathlib import Path
from urllib.request import urlopen


DESTINATION = Path(__file__).resolve().parents[1] / "photo-gallery" / "photos.js"
MIN_WIDTH = 1200


def fetch_catalog():
    photos = {}
    page = 1
    while True:
        with urlopen(
            f"https://picsum.photos/v2/list?page={page}&limit=100", timeout=30
        ) as response:
            batch = json.load(response)
        if not isinstance(batch, list):
            raise ValueError("Picsum returned an invalid catalog page")
        for photo in batch:
            photo_id = photo["id"]
            width, height = photo["width"], photo["height"]
            if (
                not isinstance(photo_id, str)
                or not photo_id.isdecimal()
                or type(width) is not int
                or type(height) is not int
                or width <= 0
                or height <= 0
            ):
                raise ValueError(f"Invalid Picsum photo: {photo!r}")
            if width >= MIN_WIDTH:
                photos[photo_id] = {"id": photo_id, "width": width, "height": height}
        if len(batch) < 100:
            break
        page += 1
    if len(photos) < 981:
        raise ValueError("The high-resolution catalog unexpectedly contains fewer than 981 photos")
    return list(photos.values())


if __name__ == "__main__":
    catalog = fetch_catalog()
    DESTINATION.write_text(
        "// Generated by scripts/update_photo_gallery_catalog.py; do not edit manually.\n"
        + "const PICSUM_PHOTOS = "
        + json.dumps(catalog, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Saved {len(catalog)} high-resolution photos to {DESTINATION}")
